'use strict';
(() => {
  const content = window.CASTDIRECTOR;
  const cards = [];

  class CapabilityCard {
    constructor(group) {
      this.group = group;
      this.pendingSeek = null;
      this.generation = 0;
      this.root = document.createElement('article');
      this.root.className = 'capability-card';
      this.root.id = group.id;
      this.root.setAttribute('role', 'tabpanel');
      this.root.setAttribute('aria-labelledby', `category-tab-${group.id}`);
      this.root.tabIndex = 0;
      this.root.hidden = group.id !== 'immersive-audio';
      const audio = group.id === 'immersive-audio';
      this.root.innerHTML = `<header class="capability-heading"><h2>${escapeHTML(group.title)}</h2><p>${escapeHTML(group.description)}</p></header>
        <div class="case-choices" role="group" aria-label="${escapeHTML(group.title)} scenes" style="--choices:${group.cases.length}">${group.cases.map((scene, index) => `<button type="button" data-choice="${index}" aria-pressed="${index === 0}" aria-label="Select ${escapeHTML(scene.title)}"><img src="${content.media[scene.media].poster}" alt="" width="84" height="50" loading="lazy"><span>${escapeHTML(scene.label)}</span></button>`).join('')}</div>
        <div class="capability-content"><div class="capability-media"><div class="case-cinema"><video playsinline preload="none"></video><button type="button" class="case-start" data-command="play"><span class="case-play-icon" aria-hidden="true">▶</span><span>Play with sound</span></button></div>
          ${audio ? `<div class="case-soundtrack"><div class="soundtrack-label"><span>Generated audio</span><output class="audio-time">0:00</output></div><div class="waveform-track"><svg viewBox="0 0 1000 64" preserveAspectRatio="none" aria-hidden="true"></svg><input type="range" class="waveform-seek" min="0" value="0" step="0.01" aria-label="Seek the selected immersive audio clip"></div><div class="audio-actions"><button type="button" class="audio-play" data-command="play">Play with sound</button><button type="button" class="case-replay" data-command="replay">Replay</button><span>Original generated audio</span></div></div>` : `<div class="case-playback-bar"><span>Generated by CastDirector</span><button type="button" class="case-replay" data-command="replay">Replay with sound</button></div>`}
          </div><div class="case-directions" aria-live="polite"></div></div>`;
      $('#category-cards').append(this.root);
      this.video = $('video', this.root);
      this.startButton = $('.case-start', this.root);
      this.wave = $('.waveform-track', this.root);
      this.root.addEventListener('click', event => {
        const choice = event.target.closest('[data-choice]');
        if (choice) { this.select(Number(choice.dataset.choice)); return; }
        const command = event.target.closest('[data-command]')?.dataset.command;
        if (command === 'play') this.video.paused ? this.play() : this.video.pause();
        if (command === 'replay') { this.seek(0); this.play(); }
      });
      this.video.addEventListener('loadedmetadata', () => {
        if (this.pendingSeek !== null) { this.video.currentTime = this.pendingSeek; this.pendingSeek = null; }
        this.updateProgress();
      });
      this.video.addEventListener('timeupdate', () => this.updateProgress());
      ['play', 'pause', 'ended'].forEach(name => this.video.addEventListener(name, () => {
        const button = $('.audio-play', this.root);
        if (button) button.textContent = this.video.ended ? 'Play again with sound' : this.video.paused ? 'Play with sound' : 'Pause';
      }));
      if (this.wave) $('input', this.wave).addEventListener('input', event => this.seek(Number(event.target.value)));
      this.select(0);
    }

    select(index) {
      this.generation++;
      this.video.pause();
      this.video.removeAttribute('src'); this.video.load();
      this.scene = this.group.cases[index];
      this.media = content.media[this.scene.media];
      this.pendingSeek = null;
      this.video.poster = this.media.poster;
      this.video.style.aspectRatio = this.media.aspect;
      this.video.controls = false;
      this.video.setAttribute('aria-label', `CastDirector: ${this.scene.title}`);
      this.startButton.hidden = false;
      $$('[data-choice]', this.root).forEach((button, i) => button.setAttribute('aria-pressed', String(i === index)));
      $('.case-directions', this.root).innerHTML = `<h3>${escapeHTML(this.scene.title)}</h3><h4>${escapeHTML(this.scene.instructionTitle)}</h4><ol>${this.scene.steps.map(step => `<li>${escapeHTML(step)}</li>`).join('')}</ol>${this.scene.constraint ? `<p class="case-constraint"><strong>Throughout the clip</strong>${escapeHTML(this.scene.constraint)}</p>` : ''}${this.scene.hint ? `<p class="listening-hint">${escapeHTML(this.scene.hint)}</p>` : ''}`;
      if (this.wave) {
        const peaks = content.waveforms[this.scene.media];
        const bars = peaks.map((level, i) => {
          const h = Math.max(3, level * 58);
          return `<rect x="${(i * 1000 / peaks.length).toFixed(2)}" y="${((64 - h) / 2).toFixed(2)}" width="4" height="${h.toFixed(2)}" rx="2"/>`;
        }).join('');
        $('svg', this.wave).innerHTML = `<defs><clipPath id="audio-progress-clip"><rect class="audio-progress" width="0" height="64"/></clipPath></defs><g fill="#b5bed8">${bars}</g><g fill="#4f63d9" clip-path="url(#audio-progress-clip)">${bars}</g><line class="audio-cursor" x1="0" x2="0" y1="0" y2="64" stroke="#19213a" stroke-width="2"/>`;
        this.updateProgress(0);
      }
    }

    hydrate() { if (!this.video.getAttribute('src')) this.video.src = this.media.src; }

    async play() {
      const generation = this.generation;
      this.hydrate(); this.video.muted = false; this.video.controls = true;
      this.startButton.hidden = true;
      try { await this.video.play(); }
      catch (error) {
        if (generation !== this.generation || error.name === 'AbortError') return;
        this.startButton.hidden = false;
        toast('Press play to start this clip.');
      }
    }

    seek(position) {
      this.hydrate();
      if (this.video.readyState >= 1) this.video.currentTime = position;
      else this.pendingSeek = position;
      this.updateProgress(position);
    }

    updateProgress(position = this.video.currentTime) {
      if (!this.wave) return;
      const duration = Number.isFinite(this.video.duration) ? this.video.duration : this.media.duration;
      const x = Math.min(999, Math.max(0, position / duration * 1000));
      $('.audio-progress', this.wave).setAttribute('width', x);
      $('.audio-cursor', this.wave).setAttribute('x1', x);
      $('.audio-cursor', this.wave).setAttribute('x2', x);
      $('input', this.wave).max = duration;
      $('input', this.wave).value = position;
      $('.audio-time', this.root).textContent = `${formatTime(position)} / ${formatTime(duration)}`;
    }
  }

  content.groups.forEach(group => cards.push(new CapabilityCard(group)));
  const categoryTabs = $$('.category-jumps [role="tab"]');
  function selectCategory(id) {
    cards.forEach(card => {
      const selected = card.group.id === id;
      card.root.hidden = !selected;
      if (!selected) { card.generation++; card.video.pause(); }
    });
    categoryTabs.forEach(tab => {
      const selected = tab.dataset.category === id;
      tab.setAttribute('aria-selected', String(selected));
      tab.tabIndex = selected ? 0 : -1;
    });
  }
  categoryTabs.forEach((tab, index) => {
    tab.addEventListener('click', () => selectCategory(tab.dataset.category));
    tab.addEventListener('keydown', event => {
      let next;
      if (event.key === 'ArrowRight') next = (index + 1) % categoryTabs.length;
      else if (event.key === 'ArrowLeft') next = (index + categoryTabs.length - 1) % categoryTabs.length;
      else if (event.key === 'Home') next = 0;
      else if (event.key === 'End') next = categoryTabs.length - 1;
      else return;
      event.preventDefault();
      selectCategory(categoryTabs[next].dataset.category);
      categoryTabs[next].focus();
    });
  });
  function selectLinkedCategory() {
    const id = location.hash.slice(1);
    if (cards.some(card => card.group.id === id)) selectCategory(id);
  }
  selectLinkedCategory();
  window.addEventListener('hashchange', selectLinkedCategory);
  $$('.author-list a[href="#"]').forEach(link => link.addEventListener('click', event => event.preventDefault()));
  document.addEventListener('play', event => {
    if (!(event.target instanceof HTMLVideoElement) || event.target.classList.contains('ambient-video')) return;
    const inComparison = event.target.closest('#evidence-host');
    if (!inComparison && comparisonPlayer) comparisonPlayer.pause();
    cards.forEach(card => { if (card.video !== event.target) card.video.pause(); });
    if (event.target !== $('#showreel-video')) $('#showreel-video').pause();
  }, true);
  const observer = new IntersectionObserver(entries => {
    for (const entry of entries) if (!entry.isIntersecting) {
      if (entry.target.id === 'evidence-host') comparisonPlayer?.pause();
      else entry.target.pause();
    }
  }, { rootMargin: '80px 0px', threshold: 0 });
  cards.forEach(card => observer.observe(card.video));
  observer.observe($('#showreel-video'));
  observer.observe($('#evidence-host'));
  document.addEventListener('visibilitychange', () => {
    if (document.hidden) { cards.forEach(card => card.video.pause()); $('#showreel-video').pause(); }
  });
})();
